# Lock file preventing concurrent sb invocations using the same build directory.
#
# The lock file is created atomically, and contains "<pid>@<hostname>@<bootid>"
# of the process holding it. A lock left behind by a process which no longer
# exists (e.g. one killed by SIGKILL), or created before the last reboot, is
# detected and removed automatically, but only if it was created on the same
# host (the cache directory might be on a network file system shared between
# machines).
#
# Be careful with imports in this file (it is used in the startup of sb).

import os

#Lock files with content which can not be parsed (e.g. if the creating process
#was killed right after creating it, before writing the content) are only
#considered stale after this many seconds (to avoid races with a process which
#is just about to write the content):
_unparsable_lock_grace_period = 30.0

def _hostname():
    import socket
    return socket.gethostname()

_cache_bootid = []
def _boot_id():
    """Identifier of the current boot of the system (or None if not available)."""
    if not _cache_bootid:
        _cache_bootid.append( _calc_boot_id() )
    return _cache_bootid[0]

def _calc_boot_id():
    #Random UUID generated by the kernel at each boot:
    import sys
    if sys.platform == 'darwin':
        b = _sysctl_string( b'kern.bootsessionuuid' )
    else:
        try:
            with open('/proc/sys/kernel/random/boot_id') as fh:#Linux
                b = fh.read()
        except (OSError,UnicodeDecodeError):
            b = None
    import re
    b = re.sub( '[^A-Za-z0-9-]', '', b or '' )
    return b or None

def _sysctl_string( name ):
    """Get string value from sysctlbyname (macOS), or None in case of
    errors."""
    try:
        import ctypes
        libc = ctypes.CDLL( None )
        f = libc.sysctlbyname
        f.restype = ctypes.c_int
        f.argtypes = [ ctypes.c_char_p, ctypes.c_void_p,
                       ctypes.POINTER(ctypes.c_size_t),
                       ctypes.c_void_p, ctypes.c_size_t ]
        buf = ctypes.create_string_buffer( 256 )
        size = ctypes.c_size_t( ctypes.sizeof(buf) )
        if f( name, buf, ctypes.byref(size), None, 0 ) != 0:
            return None
        return buf.value.decode( 'ascii', errors = 'replace' )
    except (OSError,AttributeError,ValueError,TypeError):
        return None

def lock_content():
    """The content of lock files created by the current process."""
    c = f'{os.getpid()}@{_hostname()}'
    b = _boot_id()
    return f'{c}@{b}' if b else c

def parse_lock_content( content ):
    """Returns (pid,hostname,bootid). The hostname is None for lock files
    created by older simplebuild versions (which only contained the pid), and
    the bootid is None if not available. All are None if the content can not be
    parsed."""
    content = ( content or '' ).strip()
    parts = content.split('@')
    if len(parts) > 3 or not all(parts):
        return None, None, None
    try:
        pid = int(parts[0])
    except ValueError:
        return None, None, None
    if pid <= 0:
        return None, None, None
    return ( pid,
             parts[1] if len(parts) > 1 else None,
             parts[2] if len(parts) > 2 else None )

def _process_description( pid ):
    """Short description of a running process (command and running time), or
    None if not available."""
    try:
        import subprocess
        out = subprocess.run( ['ps','-o','etime=,args=','-p',str(pid)],
                              capture_output = True, text = True,
                              timeout = 10 ).stdout.strip()
    except (OSError,subprocess.SubprocessError):
        return None
    if not out:
        return None
    etime, _, args = out.partition(' ')
    args = args.strip()
    if len(args) > 100:
        args = args[:97] + '...'
    return f'"{args}", running for {etime.strip()}'

def pid_is_alive( pid ):
    """Whether a process with the given pid exists (on the current host)."""
    try:
        os.kill( pid, 0 )
    except ProcessLookupError:
        return False
    except PermissionError:
        return True#exists, but owned by another user
    except OSError:
        return True#be conservative
    return True

class LockInfo:

    """Information about an existing lock file."""

    def __init__( self, content, mtime ):
        self.content = content
        self.pid, self.host, self.bootid = parse_lock_content( content )
        self.mtime = mtime

    def is_stale( self ):
        """Whether the lock was left behind by a process which no longer
        exists. When in doubt, the lock is not considered stale."""
        if self.pid is None:
            import time
            return ( self.mtime is not None and
                     time.time() - self.mtime > _unparsable_lock_grace_period )
        if self.host is None or self.host != _hostname():
            return False
        if self.bootid and _boot_id() and self.bootid != _boot_id():
            return True#created before the last reboot
        return not pid_is_alive( self.pid )

    def describe( self ):
        if self.pid is None:
            return 'by an unknown process'
        if self.host is None:
            return f'by process {self.pid}'
        if self.host != _hostname():
            return f'by process {self.pid} on host {self.host}'
        d = _process_description( self.pid ) if pid_is_alive( self.pid ) else None
        return f'by process {self.pid}' + ( f': {d}' if d else '' )

def read_lock( lockfile ):
    """Returns LockInfo for an existing lock file, or None if it does not
    exist."""
    try:
        mtime = lockfile.stat().st_mtime
        content = lockfile.read_text()
    except FileNotFoundError:
        return None
    except (OSError,UnicodeDecodeError):
        return LockInfo( '', None )
    return LockInfo( content, mtime )

def is_locked( lockfile ):
    """Whether the lock file exists and is not stale."""
    info = read_lock( lockfile )
    return info is not None and not info.is_stale()

def acquire( lockfile, on_stale_removal = None ):
    """Try to acquire the lock. Returns (True,content) on success, where content
    is what must later be passed to release(). Otherwise returns (False,info),
    where info is a LockInfo object describing the existing lock. Stale locks
    are removed automatically, after calling on_stale_removal(info) (if
    provided)."""
    content = lock_content()
    for _ in range(10):
        try:
            fd = os.open( lockfile, os.O_CREAT | os.O_EXCL | os.O_WRONLY, 0o644 )
        except FileExistsError:
            info = read_lock( lockfile )
            if info is None:
                continue#removed in the meantime, try again
            if not info.is_stale():
                return False, info
            if on_stale_removal:
                on_stale_removal( info )
            #Only remove the lock file if it is still the same one:
            again = read_lock( lockfile )
            if again is not None and again.content == info.content:
                try:
                    lockfile.unlink()
                except FileNotFoundError:
                    pass
            continue
        with os.fdopen( fd, 'w' ) as fh:
            fh.write( content )
        return True, content
    return False, read_lock( lockfile ) or LockInfo( '', None )

def release( lockfile, content ):
    """Release a lock acquired by acquire() (does nothing if the lock file no
    longer exists or was meanwhile created by someone else)."""
    try:
        if lockfile.read_text() == content:
            lockfile.unlink()
    except (FileNotFoundError, UnicodeDecodeError):
        pass

def exit_cleanly_on_termination_signals():
    """Make SIGTERM and SIGHUP (e.g. when a terminal is closed) result in a
    normal exit of the python process, so cleanup code like the release of
    locks is still carried out."""
    import signal
    import threading
    if threading.current_thread() is not threading.main_thread():
        return
    def handler( signum, frame ):
        raise SystemExit( 128 + signum )
    for s in ( 'SIGTERM', 'SIGHUP' ):
        sig = getattr( signal, s, None )
        if sig is not None and signal.getsignal( sig ) == signal.SIG_DFL:
            signal.signal( sig, handler )
